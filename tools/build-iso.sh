#!/usr/bin/env bash
# Build a bootable TagOS ISO with archiso.
#
# Must run on Arch Linux (mkarchiso, pacstrap, squashfs-tools, libisoburn).
# Everything the ISO needs is assembled into a throw-away staging profile:
#   build/iso-profile/tagos
# so the committed profile stays free of build artefacts and symlinks.
#
#   tools/build-iso.sh                 # build + test + ISO
#   tools/build-iso.sh --skip-build    # reuse build/arch binaries
#   tools/build-iso.sh --no-boot-test  # skip the QEMU boot verification
set -euo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD_DIR="${TAGOS_BUILD_DIR:-$ROOT/build/arch}"
STAGE="$ROOT/build/iso-profile/tagos"
WORK_DIR="$ROOT/build/archiso-work"
OUT_DIR="${TAGOS_OUT_DIR:-$ROOT/out}"
SKIP_BUILD=0
BOOT_TEST=1

usage() {
    cat <<'EOF'
usage: tools/build-iso.sh [options]

  --build-dir <dir>   CMake build directory (default build/arch)
  --out <dir>         ISO output directory (default out)
  --skip-build        do not rebuild the C++/QML binaries
  --no-boot-test      skip the QEMU boot verification
  -h, --help          this help
EOF
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --build-dir) BUILD_DIR="$2"; shift 2 ;;
        --out) OUT_DIR="$2"; shift 2 ;;
        --skip-build) SKIP_BUILD=1; shift ;;
        --no-boot-test) BOOT_TEST=0; shift ;;
        -h|--help) usage; exit 0 ;;
        *) echo "unknown option: $1" >&2; usage; exit 2 ;;
    esac
done

for tool in mkarchiso pacstrap mksquashfs xorriso; do
    command -v "$tool" >/dev/null 2>&1 || {
        echo "missing $tool — build ISOs on Arch Linux (pacman -S archiso squashfs-tools libisoburn)" >&2
        exit 127
    }
done

if [[ "$(id -u)" -ne 0 ]]; then
    echo "warning: mkarchiso usually needs root; re-run with sudo if this fails" >&2
fi

if [[ "$SKIP_BUILD" -eq 0 ]]; then
    echo "== building TagOS binaries"
    cmake -S "$ROOT" -B "$BUILD_DIR" -G Ninja \
        -DCMAKE_BUILD_TYPE=Release \
        -DCMAKE_INSTALL_PREFIX=/usr
    cmake --build "$BUILD_DIR"
    ctest --test-dir "$BUILD_DIR" --output-on-failure
fi

echo "== staging profile at $STAGE"
rm -rf "$STAGE"
mkdir -p "$STAGE"
cp -a "$ROOT/installer/archiso/tagos/." "$STAGE/"

echo "== generating packages.x86_64 from system/packages"
{
    echo "# TagOS live media package list."
    echo "#"
    echo "# GENERATED by tools/build-iso.sh from system/packages/{base,desktop,live}.txt —"
    echo "# edit those files, not this one."
    grep -hvE '^\s*(#|$)' \
        "$ROOT/system/packages/base.txt" \
        "$ROOT/system/packages/desktop.txt" \
        "$ROOT/system/packages/live.txt" \
        | sed -e 's/[[:space:]]*#.*$//' -e 's/[[:space:]]*$//' \
        | grep -v '^$' | sort -u
} >"$STAGE/packages.x86_64"

echo "== installing TagOS into airootfs"
AIROOTFS="$STAGE/airootfs"
# DESTDIR is the distro convention: binaries go to /usr, configuration to /etc,
# all inside the image root, and nothing is written to the build host.
DESTDIR="$AIROOTFS" cmake --install "$BUILD_DIR" --prefix /usr

# Fail before mkarchiso (which takes ~10 minutes) if the payload is incomplete.
required=(
    usr/bin/tag-shell
    usr/bin/tag-session
    usr/bin/tag-files
    usr/share/wayland-sessions/tagos.desktop
    usr/share/icons/hicolor/scalable/apps/tag-files.svg
    usr/lib/systemd/user/tag-shell.service
    usr/lib/systemd/user/tag-flow.service
    usr/lib/environment.d/90-tagos.conf
    etc/xdg/labwc/autostart
    etc/greetd/config.toml
)
missing=0
for file in "${required[@]}"; do
    if [[ ! -e "$AIROOTFS/$file" && ! -e "$AIROOTFS/$file.exe" ]]; then
        echo "  MISSING $file" >&2
        missing=$((missing + 1))
    fi
done
if [[ "$missing" -gt 0 ]]; then
    echo "TagOS payload is incomplete ($missing missing file(s)); refusing to build the ISO." >&2
    exit 1
fi
echo "  payload verified (${#required[@]} files)"
mkdir -p "$AIROOTFS/etc/systemd/system/multi-user.target.wants" \
         "$AIROOTFS/etc/systemd/system/graphical.target.wants"

# labwc and greetd configuration are installed straight into /etc by the CMake
# install rules, so no symlink indirection into /usr/share/tagos is needed.

# The image identifies itself as TagOS, not Arch.
ln -sfn /etc/tagos-release "$AIROOTFS/etc/os-release"

# Enable the units the live session needs.
for unit in greetd.service NetworkManager.service tagos-boot-marker.service \
            systemd-timesyncd.service bluetooth.service; do
    target="$AIROOTFS/etc/systemd/system/multi-user.target.wants/$unit"
    if [[ -f "$AIROOTFS/usr/lib/systemd/system/$unit" ]]; then
        ln -sfn "/usr/lib/systemd/system/$unit" "$target"
    else
        echo "  unit $unit is not in the image (packages.txt may be incomplete)" >&2
    fi
done

# zram keeps the live session comfortable inside a 3 GiB VM.
mkdir -p "$AIROOTFS/etc/systemd/zram-generator.conf.d"
cat >"$AIROOTFS/etc/systemd/zram-generator.conf" <<'EOF'
# TagOS live media: compressed swap in RAM.
[zram0]
zram-size = min(ram / 2, 4096)
compression-algorithm = zstd
EOF

echo "== mkarchiso"
mkdir -p "$OUT_DIR"
mkarchiso -v -w "$WORK_DIR" -o "$OUT_DIR" "$STAGE"

ISO="$(find "$OUT_DIR" -maxdepth 1 -name 'tagos-*.iso' -printf '%T@ %p\n' | sort -n | tail -1 | cut -d' ' -f2-)"
if [[ -z "$ISO" ]]; then
    echo "mkarchiso produced no ISO in $OUT_DIR" >&2
    exit 1
fi

echo "== ISO: $ISO"
sha256sum "$ISO" | tee "$ISO.sha256"

if [[ "$BOOT_TEST" -eq 1 ]]; then
    echo "== boot verification (headless QEMU/UEFI)"
    "$ROOT/tests/integration/boot-test.sh" --iso "$ISO"
fi
